create or replace function fmaint_list(p_emp text) returns jsonb
language plpgsql stable security definer set search_path to 'public' as $$
declare s foh_staff;
begin
  s := fmaint_who(p_emp);
  return jsonb_build_object(
    'cards', coalesce((select jsonb_agg(jsonb_build_object('id', c.id, 'card_no', c.card_no, 'status', c.status,
        'location', c.location, 'equipment', c.equipment, 'problem', left(c.problem, 140), 'reported_by', c.reported_by, 'reported_at', c.reported_at,
        'tech_name', c.tech_name, 'hold_reason', c.hold_reason, 'completed_at', c.completed_at, 'checked_at', c.checked_at, 'checked_by', c.checked_by,
        'sent_back_at', c.sent_back_at, 'media', jsonb_array_length(c.media), 'is_test', c.is_test,
        'photos', (select count(*) from jsonb_array_elements(c.media) m where m->>'kind' = 'photo'),
        'videos', (select count(*) from jsonb_array_elements(c.media) m where m->>'kind' = 'video'))
      order by c.reported_at desc) from fmaint_cards c
      where (c.checked_at is null or c.checked_at > now() - interval '120 days')
        and (not c.is_test or s.name ~* '^zz')), '[]'::jsonb));
end $$;

create or replace function fmaint_get(p_emp text, p_id uuid) returns jsonb
language plpgsql stable security definer set search_path to 'public' as $$
declare s foh_staff; c fmaint_cards;
begin
  s := fmaint_who(p_emp);
  select * into c from fmaint_cards where id = p_id;
  if c.id is null then raise exception 'no_card' using errcode = 'P0001'; end if;
  return jsonb_build_object('card', fmaint_card_row(c),
    'me', jsonb_build_object('tech', fmaint_has(s.id,'technician'), 'manager', fmaint_has(s.id,'manager'),
                             'signed_as_tech', c.tech_signed_id is not distinct from s.id));
end $$;

-- Opening a card as the technician is the moment it was READ.
create or replace function fmaint_read(p_emp text, p_id uuid) returns jsonb
language plpgsql security definer set search_path to 'public' as $$
declare s foh_staff; c fmaint_cards;
begin
  s := fmaint_who(p_emp);
  if not fmaint_has(s.id,'technician') then return null; end if;
  update fmaint_cards set read_at = now(), read_by = s.name,
         tech_id = coalesce(tech_id, s.id), tech_name = coalesce(tech_name, s.name),
         status = case when status = 'new' then 'acknowledged' else status end, updated_at = now()
   where id = p_id and read_at is null returning * into c;
  return case when c.id is null then null else fmaint_card_row(c) end;
end $$;

create or replace function fmaint_report(p_emp text, p_location text, p_equipment text, p_problem text, p_media jsonb) returns jsonb
language plpgsql security definer set search_path to 'public' as $$
declare s foh_staff; c fmaint_cards; m jsonb; v_media jsonb := '[]'::jsonb;
begin
  s := fmaint_who(p_emp);
  if length(trim(coalesce(p_location,''))) < 2 then raise exception 'no_location' using errcode = 'P0001'; end if;
  if length(trim(coalesce(p_equipment,''))) < 2 then raise exception 'no_equipment' using errcode = 'P0001'; end if;
  if length(trim(coalesce(p_problem,''))) < 3 then raise exception 'no_problem' using errcode = 'P0001'; end if;
  if jsonb_typeof(coalesce(p_media,'[]'::jsonb)) <> 'array' or jsonb_array_length(coalesce(p_media,'[]'::jsonb)) > 8 then raise exception 'bad_media' using errcode = 'P0001'; end if;
  for m in select * from jsonb_array_elements(coalesce(p_media,'[]'::jsonb)) loop
    if coalesce(m->>'path','') !~ '^c/[0-9a-f-]{36}/[A-Za-z0-9._-]+$'
       or not exists(select 1 from storage.objects o where o.bucket_id = 'fmaint-media' and o.name = m->>'path') then
      raise exception 'bad_media' using errcode = 'P0001'; end if;
    v_media := v_media || jsonb_build_array(jsonb_build_object('path', m->>'path',
      'kind', case when m->>'kind' = 'video' then 'video' else 'photo' end, 'size', coalesce((m->>'size')::bigint, 0)));
  end loop;
  insert into fmaint_cards(is_test, reported_by_id, reported_by, location, equipment, problem, media)
  values (s.name ~* '^zz' or trim(p_equipment) ~* '^zz', s.id, s.name, left(trim(p_location),120), left(trim(p_equipment),120), left(trim(p_problem),2000), v_media)
  returning * into c;
  perform fmaint_queue(c.id, 'new');
  return jsonb_build_object('id', c.id, 'card_no', c.card_no, 'is_test', c.is_test);
end $$;

create or replace function fmaint_amount(p text) returns numeric
language plpgsql immutable as $$
begin
  if p is null or trim(p) = '' then return null; end if;
  if trim(p) !~ '^\d{1,7}(\.\d{1,2})?$' then raise exception 'bad_amount' using errcode = 'P0001'; end if;
  return trim(p)::numeric;
end $$;

create or replace function fmaint_step(p_emp text, p_id uuid, p_op text, p_args jsonb) returns jsonb
language plpgsql security definer set search_path to 'public' as $$
declare s foh_staff; c fmaint_cards; a jsonb := coalesce(p_args,'{}'::jsonb); v_tech boolean; v_mgr boolean;
begin
  s := fmaint_who(p_emp);
  v_tech := fmaint_has(s.id,'technician'); v_mgr := fmaint_has(s.id,'manager');
  select * into c from fmaint_cards where id = p_id for update;
  if c.id is null then raise exception 'no_card' using errcode = 'P0001'; end if;
  if c.checked_at is not null then raise exception 'closed' using errcode = 'P0001'; end if;

  if p_op in ('start','hold','resume','assess','complete') then
    if not v_tech then raise exception 'not_tech' using errcode = 'P0001'; end if;
    if c.status = 'completed' then raise exception 'completed' using errcode = 'P0001'; end if;
    update fmaint_cards set read_at = coalesce(read_at, now()), read_by = coalesce(read_by, s.name),
           tech_id = coalesce(tech_id, s.id), tech_name = coalesce(tech_name, s.name) where id = p_id;
  end if;

  if p_op = 'start' then
    update fmaint_cards set status = 'in_progress', started_at = coalesce(started_at, now()), hold_reason = null, updated_at = now() where id = p_id;
  elsif p_op = 'hold' then
    update fmaint_cards set status = 'on_hold', hold_at = now(), hold_reason = nullif(left(trim(coalesce(a->>'reason','')),200),''), updated_at = now() where id = p_id;
  elsif p_op = 'resume' then
    if c.status <> 'on_hold' then raise exception 'not_on_hold' using errcode = 'P0001'; end if;
    update fmaint_cards set status = 'in_progress', started_at = coalesce(started_at, now()), hold_reason = null, updated_at = now() where id = p_id;
  elsif p_op = 'assess' then
    update fmaint_cards set
      diagnosis = nullif(left(trim(coalesce(a->>'diagnosis','')),2000),''),
      cause     = nullif(left(trim(coalesce(a->>'cause','')),1000),''),
      solution  = nullif(left(trim(coalesce(a->>'solution','')),1000),''),
      est_cost  = fmaint_amount(a->>'est_cost'),
      est_time  = nullif(left(trim(coalesce(a->>'est_time','')),120),''),
      parts     = nullif(left(trim(coalesce(a->>'parts','')),1000),''),
      notes     = nullif(left(trim(coalesce(a->>'notes','')),2000),''),
      assessed_at = now(), assessed_by = s.name, updated_at = now()
    where id = p_id;
  elsif p_op = 'complete' then
    if trim(coalesce(a->>'code','')) <> trim(s.emp_id) then raise exception 'bad_code' using errcode = 'P0001'; end if;
    if length(trim(coalesce(a->>'work_done',''))) < 3 then raise exception 'no_work' using errcode = 'P0001'; end if;
    if fmaint_amount(a->>'final_cost') is null then raise exception 'no_cost' using errcode = 'P0001'; end if;
    update fmaint_cards set status = 'completed', work_done = left(trim(a->>'work_done'),2000), final_cost = fmaint_amount(a->>'final_cost'),
           completed_at = now(), tech_signed_id = s.id, tech_signed_by = s.name, hold_reason = null, updated_at = now()
     where id = p_id;
    perform fmaint_queue(p_id, 'check');
  elsif p_op = 'check' then
    if not v_mgr then raise exception 'not_manager' using errcode = 'P0001'; end if;
    if c.status <> 'completed' then raise exception 'not_completed' using errcode = 'P0001'; end if;
    if trim(coalesce(a->>'code','')) <> trim(s.emp_id) then raise exception 'bad_code' using errcode = 'P0001'; end if;
    if c.tech_signed_id = s.id then raise exception 'same_person' using errcode = 'P0001'; end if;
    update fmaint_cards set checked_at = now(), checked_id = s.id, checked_by = s.name, updated_at = now() where id = p_id;
  elsif p_op = 'send_back' then
    if not v_mgr then raise exception 'not_manager' using errcode = 'P0001'; end if;
    if c.status <> 'completed' then raise exception 'not_completed' using errcode = 'P0001'; end if;
    if length(trim(coalesce(a->>'note',''))) < 3 then raise exception 'no_note' using errcode = 'P0001'; end if;
    update fmaint_cards set status = 'in_progress', completed_at = null, tech_signed_id = null, tech_signed_by = null,
           sent_back_at = now(), sent_back_by = s.name, sent_back_note = left(trim(a->>'note'),500), updated_at = now() where id = p_id;
  else
    raise exception 'bad_op' using errcode = 'P0001';
  end if;
  select * into c from fmaint_cards where id = p_id;
  return fmaint_card_row(c);
end $$;

