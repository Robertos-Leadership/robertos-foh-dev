create table if not exists fmaint_people (
  staff_id uuid not null references foh_staff(id),
  role text not null check (role in ('technician','manager')),
  email text not null,
  active boolean not null default true,
  primary key (staff_id, role)
);

create table if not exists fmaint_cards (
  id uuid primary key default gen_random_uuid(),
  card_no bigint generated by default as identity unique,
  is_test boolean not null default false,
  reported_by_id uuid, reported_by text not null, reported_at timestamptz not null default now(),
  location text not null, equipment text not null, problem text not null,
  media jsonb not null default '[]'::jsonb,
  status text not null default 'new' check (status in ('new','acknowledged','in_progress','on_hold','completed')),
  read_at timestamptz, read_by text,
  tech_id uuid, tech_name text,
  started_at timestamptz, hold_at timestamptz, hold_reason text,
  diagnosis text, cause text, solution text, est_cost numeric(12,2), est_time text, parts text, notes text,
  assessed_at timestamptz, assessed_by text,
  work_done text, final_cost numeric(12,2), completed_at timestamptz,
  tech_signed_id uuid, tech_signed_by text,
  checked_at timestamptz, checked_id uuid, checked_by text,
  sent_back_at timestamptz, sent_back_by text, sent_back_note text,
  updated_at timestamptz not null default now()
);
create index if not exists fmaint_cards_open on fmaint_cards(checked_at, status);

create table if not exists fmaint_mail (
  id bigint generated by default as identity primary key,
  card_id uuid not null references fmaint_cards(id) on delete cascade,
  kind text not null check (kind in ('new','check')),
  to_list text[] not null,
  is_test boolean not null default false,
  status text not null default 'queued' check (status in ('queued','sending','sent','failed')),
  tries int not null default 0,
  resend_id text, error text,
  created_at timestamptz not null default now(), sent_at timestamptz
);
create index if not exists fmaint_mail_status on fmaint_mail(status, created_at);

