create or replace function fmaint_queue(p_card uuid, p_kind text) returns void
language plpgsql security definer set search_path to 'public' as $$
declare c fmaint_cards; v_to text[]; v_id bigint;
begin
  select * into c from fmaint_cards where id = p_card;
  if c.is_test then v_to := array['fguarracino@robertos.ae'];
  else
    if p_kind = 'new' then
      select array_agg(distinct lower(email)) into v_to from fmaint_people where active and role = 'technician';
    end if;
    -- 'check' always goes to the managers; 'new' does too while there is no technician
    if v_to is null or cardinality(v_to) = 0 then
      select array_agg(distinct lower(email)) into v_to from fmaint_people where active and role = 'manager';
    end if;
  end if;
  if v_to is null or cardinality(v_to) = 0 then return; end if;
  insert into fmaint_mail(card_id, kind, to_list, is_test) values (p_card, p_kind, v_to, c.is_test) returning id into v_id;
  perform fmaint_kick(v_id);
end $$;
revoke all on function fmaint_queue(uuid,text) from public, anon, authenticated;

